def filter_assets(filters=None, tenant_context=None):
    filters = filters or {}
    queryset = filter_records_for_scope(deepcopy(ASSET_RECORDS), tenant_context or {})
    search = _normalize(filters.get("search", ""))
    if search:
        queryset = [
            asset
            for asset in queryset
            if search in _normalize(asset["code"])
            or search in _normalize(asset["name"])
            or search in _normalize(asset["description"])
        ]

    equality_map = {
        "client": "client",
        "site": "site",
        "category": "category",
        "criticality": "criticality",
        "status": "operational_status",
        "condition": "condition",
        "manufacturer": "manufacturer",
    }
    for filter_key, asset_key in equality_map.items():
        value = filters.get(filter_key, "")
        if value:
            queryset = [asset for asset in queryset if asset[asset_key] == value]

    if filters.get("preventive") == "without":
        queryset = [asset for asset in queryset if asset["without_plan"]]
    elif filters.get("preventive") == "with":
        queryset = [asset for asset in queryset if not asset["without_plan"]]

    if filters.get("work_orders") == "with":
        queryset = [asset for asset in queryset if asset["has_open_work_order"]]
    elif filters.get("work_orders") == "without":
        queryset = [asset for asset in queryset if not asset["has_open_work_order"]]

    return queryset


