def get_asset_by_code(asset_code, tenant_context=None):
    target = _normalize(asset_code)
    for asset in ASSET_RECORDS:
        if _normalize(asset["code"]) == target and record_matches_scope(asset, tenant_context or {}):
            return deepcopy(asset)
    return None


